import {chromium,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await mkdir('artifacts',{recursive:true});
try {
  await page.goto('http://localhost:30080/');
  await expect(page.getByRole('button',{name:'Create an account',exact:true})).toBeEnabled({timeout:30000});
  await page.screenshot({path:'artifacts/account-welcome.png',fullPage:true});
  await page.getByRole('button',{name:'Create an account',exact:true}).click();
  await page.locator('#kc-register-form').waitFor({timeout:60000});
  await expect(page.getByRole('textbox',{name:'Email',exact:true})).toBeVisible();
  await page.screenshot({path:'artifacts/account-register.png',fullPage:true});
  await page.goto('http://localhost:30080/');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await page.locator('#username').waitFor({timeout:60000});
  await page.screenshot({path:'artifacts/account-login.png',fullPage:true});
  await page.locator('#username').fill('notification-check');
  await page.locator('#password').fill('local-check-only');
  await page.locator('#kc-login').click();
  await expect(page.getByRole('heading',{name:'A clearer view of your money.'})).toBeVisible({timeout:90000});
  await page.getByRole('navigation',{name:'Main navigation'}).getByRole('button',{name:'Activity',exact:true}).click();
  await page.getByRole('button',{name:'Add entry',exact:true}).click();
  const dialog=page.getByRole('dialog');
  const description=`Account browser check ${Date.now()}`;
  await dialog.getByRole('textbox',{name:'Amount in INR'}).fill('123.45');
  await dialog.getByLabel('Merchant / description').fill(description);
  await dialog.getByRole('button',{name:'Save entry',exact:true}).click();
  await expect(dialog).toHaveCount(0,{timeout:45000});
  await expect(page.getByRole('table').getByText(description)).toBeVisible();
  await page.reload();
  await expect(page.getByRole('table').getByText(description)).toBeVisible({timeout:45000});
  await page.screenshot({path:'artifacts/account-activity.png',fullPage:true});
  await page.getByRole('table').getByText(description).click();
  await page.getByRole('button',{name:'Delete transaction',exact:true}).click();
  await page.getByRole('button',{name:'Confirm change',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0,{timeout:45000});
  await expect(page.getByRole('table').getByText(description)).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  console.log('PASS: matching registration/login screens, real PKCE login, server-confirmed expense save, reload persistence, deletion and mobile bounds.');
}catch(error){await page.screenshot({path:'artifacts/account-browser-error.png',fullPage:true});throw error;}finally{await browser.close();}
