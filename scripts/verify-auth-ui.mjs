import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1280,height:950}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await mkdir('artifacts',{recursive:true});
try {
  await page.goto('http://localhost:30080');
  await page.getByRole('button',{name:'Create an account',exact:true}).click();
  await page.locator('#kc-register-form').waitFor();
  const password = page.locator('#password');
  await password.fill('tiny');
  const toggle = page.locator('[data-password-toggle][aria-controls=password]');
  await toggle.click();await expect(password).toHaveAttribute('type','text');
  await expect(toggle).toHaveAttribute('aria-pressed','true');
  await expect(toggle.locator('img')).toHaveJSProperty('complete',true);
  expect(await toggle.locator('img').evaluate(img=>img.naturalWidth)).toBeGreaterThan(0);
  await toggle.click();await expect(password).toHaveAttribute('type','password');
  await page.getByLabel('Email',{exact:true}).fill(`ui-validation-${Date.now()}@example.test`);
  await page.getByLabel('First name',{exact:true}).fill('UI');
  await page.getByLabel('Last name',{exact:true}).fill('Validation');
  await page.locator('#password-confirm').fill('tiny');
  const before = await password.boundingBox();
  await page.locator('#kc-register-form input[type=submit]').click();
  await expect(page.locator('#input-error-password')).toBeVisible();
  const after = await password.boundingBox();
  expect(Math.abs(before.width-after.width)).toBeLessThan(1);
  expect(after.height).toBe(44);
  await password.click();
  await expect(password).toHaveCSS('outline-style','none');
  await page.screenshot({path:'artifacts/auth-validation-fixed.png',fullPage:true});
  await page.getByRole('link',{name:/Back to Login/i}).click();
  await page.locator('#password').fill('visibility-check');
  await expect(page.locator('[data-password-toggle]')).toBeEnabled();
  await expect(page.locator('[data-password-toggle] img')).toHaveJSProperty('complete',true);
  await page.locator('[data-password-toggle]').click();
  await expect(page.locator('#password')).toHaveAttribute('type','text');
  await expect(page.locator('[data-password-toggle]')).toHaveAttribute('aria-pressed','true');
  await expect(page.locator('[data-password-toggle] img')).toHaveAttribute('src',/eye-off\.svg$/);
  await page.screenshot({path:'artifacts/auth-login-fixed.png',fullPage:true});
  expect(errors).toEqual([]);
  console.log('PASS login/registration password toggles, real minimum-length error layout, field focus and loaded Lucide assets. No account created or external email sent.');
} finally {await browser.close();}
